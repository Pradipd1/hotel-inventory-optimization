import { z } from 'zod';
import { ALL_PO_STATUS } from '../utils/constants.js';
import { dateString, nullableNonNegative, objectId, optionalString, pagination } from './common.js';

export const supplierSchema = z.object({
  name: z.string().trim().min(2, 'Name must be at least 2 characters').max(120),
  companyName: optionalString(150),
  contactPerson: optionalString(100),
  email: z
    .union([z.string().trim().toLowerCase().email('Enter a valid email'), z.literal('')])
    .optional()
    .transform((v) => (v === '' ? undefined : v)),
  phone: z
    .string()
    .trim()
    .max(40)
    .regex(/^[0-9+()\-\s]*$/, 'Phone may contain digits, spaces, +, - and brackets')
    .optional(),
  address: optionalString(300),
  paymentTerms: optionalString(100),
  leadTimeDays: nullableNonNegative,
  status: z.enum(['active', 'inactive']).default('active'),
  notes: optionalString(1000),
});

export const supplierUpdateSchema = supplierSchema.partial();

export const supplierListQuery = z.object({
  ...pagination,
  search: z.string().trim().max(100).optional(),
  status: z.enum(['active', 'inactive']).optional(),
});

// ---------- Purchase orders ----------
const poLine = z.object({
  item: objectId,
  quantity: z.number({ invalid_type_error: 'Quantity must be a number' }).positive('Quantity must be greater than zero').max(1e7),
  unitPrice: z.number().min(0, 'Price cannot be negative').optional(),
});

export const purchaseOrderSchema = z.object({
  supplier: objectId,
  items: z.array(poLine).min(1, 'Add at least one item').max(100),
  taxRate: z.number().min(0).max(100).optional(),
  notes: optionalString(2000),
  expectedDeliveryDate: z
    .union([dateString, z.literal(''), z.null()])
    .optional()
    .transform((v) => (v ? new Date(v) : null)),
});

export const poListQuery = z.object({
  ...pagination,
  status: z.enum(ALL_PO_STATUS).optional(),
  supplier: objectId.optional(),
  search: z.string().trim().max(60).optional(),
  from: dateString.optional(),
  to: dateString.optional(),
});

export const poNoteSchema = z.object({ note: optionalString(500) });

export const receiveSchema = z.object({
  // Generated by the client when the receive form opens; resubmitting the same key is rejected.
  idempotencyKey: z.string().trim().min(8).max(100),
  lines: z
    .array(z.object({ lineId: objectId, quantity: z.number().min(0).max(1e7) }))
    .min(1),
  notes: optionalString(500),
});

export const fromRecommendationsSchema = z.object({
  items: z
    .array(z.object({ item: objectId, quantity: z.number().positive().max(1e7) }))
    .min(1, 'Select at least one recommendation')
    .max(100),
});
